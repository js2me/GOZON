export function mockReview(id: number, index: number) {
  const slot = (id + index) % impressions.length;
  return {
    author: authors[slot],
    date: new Date(Date.UTC(2026, 9, 28 - index * 3 - (id % 7)))
      .toISOString()
      .slice(0, 10),
    stars: [5, 5, 4, 5, 5, 3, 5, 4][slot],
    text: (id === 34 ? catToyReviews[index] : undefined) ?? impressions[slot],
  };
}

export function productFeedback(
  product: ProductDC,
  shop: string,
): ProductFeedback {
  const toy = product.id === 34;
  const facts = product.characteristics.filter(
    (item) => !['Артикул', 'Категория', 'Наименование'].includes(item.label),
  );
  const questions = [
    {
      question: toy ? 'У игрушки есть колокольчик?' : 'Кто продаёт этот товар?',
      answer: toy
        ? 'Да, к игрушке прикреплён небольшой колокольчик.'
        : `Продавец товара — ${shop}.`,
    },
    {
      question: toy
        ? 'Из чего сделана верёвка?'
        : 'Сколько дней даётся на возврат?',
      answer: toy
        ? 'В этой модели используется хлопковая верёвка.'
        : `Срок возврата — ${product.returnPeriodDays} дней.`,
    },
    {
      question: toy
        ? 'Можно выбрать цвет мячика?'
        : 'Как узнать артикул для повторного заказа?',
      answer: toy
        ? 'Цвет мячика случайный и может отличаться от фото.'
        : `Артикул этой модели — ${product.id}. Его также можно посмотреть в характеристиках.`,
    },
  ];
  return {
    description: toy
      ? 'Игрушка для кошек с палочкой мататаби, мячиком и натуральным пером. Детали соединены хлопковой верёвкой. При движении звенит маленький колокольчик. Цвет мячика может отличаться от фотографии.'
      : [
          product.title,
          ...facts.map((f) => `${f.label} — ${f.value}`),
          `Продавец — ${shop}`,
        ].join('. ') + '.',
    reviews: Array.from({ length: product.reviewsCount }, (_, i) =>
      mockReview(product.id, i),
    ),
    questions: questions.map((q, i) => ({
      ...q,
      author: authors[(product.id + i + 1) % authors.length],
    })),
  };
}
